print('Вычисление дохода по вкладу.', end='\n\n')
print('Введите исходные данные:', end='\n\n')
s = int(input('Сумма вклада (руб.) -> '))
n = int(input('Срок вклада -> '))
p = float(input('Процентная ставка (годовых) -> '))
print(f'\nДоход по вкладу:\t\t\t\t  {(a := s * (p / 100) * (n / 12))}')
print(f'Сумма по окончании срока вклада: {s + a}')
